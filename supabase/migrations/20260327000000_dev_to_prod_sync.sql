CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  insert into public.parent_profiles (
    id,
    username,
    credits,
    created_at,
    updated_at
  )
  values (
    new.id,
    new.email,
    CASE WHEN (new.raw_user_meta_data->>'is_free_trial')::boolean = true THEN 2 ELSE 0 END,
    now(),
    now()
  )
  on conflict (id) do update
  set username = excluded.username,
      credits = CASE 
        WHEN parent_profiles.credits IS NULL OR parent_profiles.credits = 0 
        THEN excluded.credits 
        ELSE parent_profiles.credits 
      END,
      updated_at = now();

  return new;
end;
$function$
;

CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

